$ErrorActionPreference = "Stop"

# Portable Discord Presence build script.
# Uses the C# compiler that ships with the .NET Framework, so no SDK or
# package installs are needed. Output: dist\DiscordPresence.exe (single file).

$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$csc = Join-Path $env:WINDIR "Microsoft.NET\Framework64\v4.0.30319\csc.exe"
if (-not (Test-Path $csc)) {
    $csc = Join-Path $env:WINDIR "Microsoft.NET\Framework\v4.0.30319\csc.exe"
}
if (-not (Test-Path $csc)) {
    throw "Could not find the .NET Framework compiler. Install .NET Framework 4.8."
}

$gac = Join-Path $env:WINDIR "Microsoft.NET\assembly"
$refs = @(
    (Join-Path $gac "GAC_MSIL\PresentationFramework\v4.0_4.0.0.0__31bf3856ad364e35\PresentationFramework.dll"),
    (Join-Path $gac "GAC_32\PresentationCore\v4.0_4.0.0.0__31bf3856ad364e35\PresentationCore.dll"),
    (Join-Path $gac "GAC_MSIL\WindowsBase\v4.0_4.0.0.0__31bf3856ad364e35\WindowsBase.dll"),
    (Join-Path $gac "GAC_MSIL\System.Xaml\v4.0_4.0.0.0__b77a5c561934e089\System.Xaml.dll"),
    # The colour rails expose themselves as sliders to screen readers and
    # automation, which needs the UIA provider interfaces.
    (Join-Path $gac "GAC_MSIL\UIAutomationProvider\v4.0_4.0.0.0__31bf3856ad364e35\UIAutomationProvider.dll"),
    (Join-Path $gac "GAC_MSIL\UIAutomationTypes\v4.0_4.0.0.0__31bf3856ad364e35\UIAutomationTypes.dll")
)
foreach ($ref in $refs) {
    if (-not (Test-Path $ref)) { throw "Missing framework assembly: $ref" }
}

Write-Host "Building app icon..." -ForegroundColor DarkGray
$iconToolDir = Join-Path $root "tools\bin"
New-Item -ItemType Directory -Force $iconToolDir | Out-Null
$iconTool = Join-Path $iconToolDir "IconGen.exe"
$iconSources = @(
    (Join-Path $root "src\Brand.cs"),
    (Join-Path $root "tools\IconGen.cs")
)
$iconArgs = @("-nologo", "-target:exe", "-platform:x86", "-optimize+", "-out:$iconTool") +
    ($refs | ForEach-Object { "-r:$_" }) + $iconSources
& $csc @iconArgs
if ($LASTEXITCODE -ne 0) { throw "Icon generator failed to compile." }
& $iconTool $root
if ($LASTEXITCODE -ne 0) { throw "Icon generation failed." }

Write-Host "Stamping build date..." -ForegroundColor DarkGray
$builtAt = Get-Date -Format "yyyy-MM-dd HH:mm"
$buildInfo = Join-Path $root "src\BuildInfo.cs"
@"
// Generated by build.ps1 at compile time. Do not edit by hand.
namespace DiscordPresence
{
    internal static class BuildInfo
    {
        public const string Built = "$builtAt";
    }
}
"@ | Set-Content -Path $buildInfo -Encoding ASCII

Write-Host "Building DiscordPresence.exe..." -ForegroundColor DarkGray
$dist = Join-Path $root "dist"
New-Item -ItemType Directory -Force $dist | Out-Null
$exe = Join-Path $dist "DiscordPresence.exe"
$sources = Get-ChildItem (Join-Path $root "src") -Filter "*.cs" | ForEach-Object { $_.FullName }
$appArgs = @(
    "-nologo",
    "-target:winexe",
    "-platform:x86",
    "-optimize+",
    "-out:$exe",
    "-win32icon:$(Join-Path $root 'assets\discord.ico')",
    "-win32manifest:$(Join-Path $root 'app.manifest')"
) + ($refs | ForEach-Object { "-r:$_" }) + $sources

& $csc @appArgs
if ($LASTEXITCODE -ne 0) { throw "Build failed." }

$size = [math]::Round((Get-Item $exe).Length / 1KB)
Write-Host "Done: $exe ($size KB)" -ForegroundColor Green
